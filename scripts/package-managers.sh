#!/usr/bin/env bash
# Write the Homebrew formula (Formula/koru.rb) and the Scoop manifest
# (bucket/koru.json) for a release, from its SHA256SUMS. Both live in this
# repository, which is also the Homebrew tap and the Scoop bucket:
#
#   brew tap wux4an/koru https://github.com/wux4an/koru && brew install koru
#   scoop bucket add koru https://github.com/wux4an/koru && scoop install koru
#
#   scripts/package-managers.sh v0.0.1 path/to/SHA256SUMS
set -euo pipefail

tag="${1:?usage: scripts/package-managers.sh vX.Y.Z SHA256SUMS}"
sums="${2:?usage: scripts/package-managers.sh vX.Y.Z SHA256SUMS}"
[[ "$tag" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]] || {
  echo "package-managers: '$tag' must be a stable tag like v0.0.1" >&2
  exit 1
}
version="${tag#v}"
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
download="https://github.com/wux4an/koru/releases/download"

hash_of() {
  local name="koru_${version}_$1" sum
  sum="$(awk -v f="$name" '$2 == f || $2 == "*" f { print $1 }' "$sums")"
  [[ "$sum" =~ ^[0-9a-f]{64}$ ]] || {
    echo "package-managers: $sums has no SHA-256 for $name" >&2
    exit 1
  }
  printf '%s' "$sum"
}

# Look every hash up first: an exit inside \$(...) would not stop the script.
declare -A sha
for target in darwin_arm64.tar.gz darwin_amd64.tar.gz linux_arm64.tar.gz linux_amd64.tar.gz windows_amd64.zip windows_arm64.zip; do
  sha[$target]="$(hash_of "$target")" || exit 1
done

mkdir -p "$root/Formula" "$root/bucket"
cat >"$root/Formula/koru.rb" <<RUBY
# Generated by scripts/package-managers.sh for koru $tag. Do not edit.
class Koru < Formula
  desc "Build signed Android apps from HTML, CSS and JavaScript, without Java or Gradle"
  homepage "https://koru.js.org"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$download/$tag/koru_${version}_darwin_arm64.tar.gz"
      sha256 "${sha[darwin_arm64.tar.gz]}"
    end
    on_intel do
      url "$download/$tag/koru_${version}_darwin_amd64.tar.gz"
      sha256 "${sha[darwin_amd64.tar.gz]}"
    end
  end

  on_linux do
    on_arm do
      url "$download/$tag/koru_${version}_linux_arm64.tar.gz"
      sha256 "${sha[linux_arm64.tar.gz]}"
    end
    on_intel do
      url "$download/$tag/koru_${version}_linux_amd64.tar.gz"
      sha256 "${sha[linux_amd64.tar.gz]}"
    end
  end

  def install
    bin.install "koru"
  end

  test do
    assert_match "koru #{version}", shell_output("#{bin}/koru version")
  end
end
RUBY

cat >"$root/bucket/koru.json" <<JSON
{
  "version": "$version",
  "description": "Build signed Android apps from HTML, CSS and JavaScript, without Java or Gradle",
  "homepage": "https://koru.js.org",
  "license": "MIT",
  "architecture": {
    "64bit": {
      "url": "$download/$tag/koru_${version}_windows_amd64.zip",
      "hash": "${sha[windows_amd64.zip]}",
      "extract_dir": "koru_${version}_windows_amd64"
    },
    "arm64": {
      "url": "$download/$tag/koru_${version}_windows_arm64.zip",
      "hash": "${sha[windows_arm64.zip]}",
      "extract_dir": "koru_${version}_windows_arm64"
    }
  },
  "bin": "koru.exe",
  "checkver": "github",
  "autoupdate": {
    "architecture": {
      "64bit": {
        "url": "$download/v\$version/koru_\$version_windows_amd64.zip",
        "extract_dir": "koru_\$version_windows_amd64"
      },
      "arm64": {
        "url": "$download/v\$version/koru_\$version_windows_arm64.zip",
        "extract_dir": "koru_\$version_windows_arm64"
      }
    },
    "hash": {
      "url": "\$url.sha256"
    }
  }
}
JSON
echo "Wrote Formula/koru.rb and bucket/koru.json for $tag"
